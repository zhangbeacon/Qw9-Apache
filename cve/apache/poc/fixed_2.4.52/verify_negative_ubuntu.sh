#!/bin/bash
# 修复版负向对照：Ubuntu 22.04 发行版的 Apache/2.4.52 (Ubuntu)
#   41773：路径穿越/文件读/RCE 应全部失败
#   44224：forward proxy unix: URI 应 400，UDS 后端收不到请求
#   44790：parsebody 应正常返回，不再 SIGSEGV/Abort
# 退出码 0 = 三个 CVE 在 2.4.52 上均不再命中
set -u
ROOT="/mnt/e/强网拟态/cve/apache"
EVID="$ROOT/evidence"
PREFIX=/tmp/httpd252-root
BIN=/usr/sbin/apache2
MODS=/usr/lib/apache2/modules
PORT=8082
BASE="http://127.0.0.1:$PORT"
mkdir -p "$PREFIX/conf" "$PREFIX/logs" "$PREFIX/htdocs" "$PREFIX/icons" "$PREFIX/cgi-bin" "$PREFIX/lua"
cp -f /opt/httpd/conf/mime.types "$PREFIX/conf/mime.types" 2>/dev/null || true
echo '<html><body>fixed 2.4.52 lab</body></html>' > "$PREFIX/htdocs/index.html"

{
  echo "== fixed version =="
  "$BIN" -v
  sha256sum "$BIN"
  dpkg-query -W -f='apache2-bin=${Version}\n' apache2-bin 2>/dev/null
  echo "note: Ubuntu 22.04 发行版 2.4.52（含 41773/44224/44790 上游修复）"
  echo "modules: $MODS"
} > "$EVID/fixed_2.4.52_build.txt"

prep_conf() { # $1=src $2=dst
  sed -e 's#^LoadModule unixd_module.*#\# unixd is static#' \
      -e 's#^LoadModule log_config_module.*#\# log_config is static#' \
      -e "s#modules/#$MODS/#g" \
      -e "s#/opt/httpd#$PREFIX#g" \
      -e 's#^ServerRoot.*#ServerRoot "/tmp/httpd252-root"#' \
      "$1" > "$2"
  sed -i '1i LoadModule mpm_event_module /usr/lib/apache2/modules/mod_mpm_event.so' "$2"
  sed -i '1i # generated by verify_negative_ubuntu.sh for Apache/2.4.52 (Ubuntu)' "$2"
}
stop_srv() { pkill -f "httpd252-root" 2>/dev/null || true; pkill -f "$BIN -f $PREFIX" 2>/dev/null || true; sleep 0.6; }
start_srv() { # $1 conf path
  stop_srv
  cd "$PREFIX"; : > logs/error_log; : > logs/access_log
  "$BIN" -f "$1" -DFOREGROUND > "$PREFIX/logs/console.log" 2>&1 &
  HPID=$!
  for i in $(seq 1 40); do curl -s -o /dev/null "$BASE/" && break; sleep 0.25; done
  if ! curl -s -o /dev/null "$BASE/"; then
    echo "2.4.52 START FAILED"; tail -20 "$PREFIX/logs/console.log" "$PREFIX/logs/error_log" 2>/dev/null; return 1
  fi
}

### 41773 ###
echo "== [41773] fixed 2.4.52 negative =="
prep_conf "$ROOT/conf/httpd.conf" "$PREFIX/conf/httpd-41773.conf"
start_srv "$PREFIX/conf/httpd-41773.conf" || exit 2
{
  echo "== Apache/2.4.52 (Ubuntu) negative control for CVE-2021-41773 =="
  "$BIN" -v
  echo
  echo "== file read /etc/passwd =="
  curl -sS -i --path-as-is "$BASE/icons/.%2e/.%2e/.%2e/.%2e/etc/passwd" | head -15
  echo "== file read secret =="
  curl -sS -i --path-as-is "$BASE/icons/.%2e/.%2e/.%2e/.%2e/opt/httpd-secret-41773.txt" | head -15
  echo "== CGI traversal /bin/sh =="
  curl -sS -i --path-as-is "$BASE/cgi-bin/.%2e/.%2e/.%2e/.%2e/bin/sh" \
    --data-binary $'echo Content-Type: text/plain\necho\nid' | head -20
  echo "== error_log tail =="; tail -6 "$PREFIX/logs/error_log"
} > "$EVID/CVE-2021-41773/fixed_2.4.52_negative.txt" 2>&1
R1=0
grep -q 'root:x:0:0' "$EVID/CVE-2021-41773/fixed_2.4.52_negative.txt" && R1=1
grep -q 'LAB_SECRET_OUTSIDE_DOCROOT_41773' "$EVID/CVE-2021-41773/fixed_2.4.52_negative.txt" && R1=1
grep -q 'uid=' "$EVID/CVE-2021-41773/fixed_2.4.52_negative.txt" && R1=1
stop_srv
echo "41773 fixed_hit(should 0)=$R1"

### 44224 ###
echo "== [44224] fixed 2.4.52 negative =="
prep_conf "$ROOT/conf/httpd-44224.conf" "$PREFIX/conf/httpd-44224.conf"
DECL=/tmp/cve-2021-44224.sock
EVIL=/tmp/cve-2021-44224-evil.sock
rm -f "$DECL" "$EVIL" /tmp/fixed-decl.log /tmp/fixed-evil.log
UDS_PATH="$DECL" python3 "$ROOT/poc/CVE-2021-44224/uds_backend.py" /tmp/fixed-decl.log "SECRET_FROM_UDS_DECLARED" &
UP1=$!
UDS_PATH="$EVIL" python3 "$ROOT/poc/CVE-2021-44224/uds_backend.py" /tmp/fixed-evil.log "SECRET_FROM_UDS_ARBITRARY" &
UP2=$!
for i in $(seq 1 40); do [ -S "$DECL" ] && [ -S "$EVIL" ] && break; sleep 0.1; done
start_srv "$PREFIX/conf/httpd-44224.conf" || exit 2
{
  echo "== Apache/2.4.52 (Ubuntu) negative control for CVE-2021-44224 =="
  "$BIN" -v
  echo
  echo "== A: declared UDS URI =="
  python3 "$ROOT/poc/CVE-2021-44224/poc.py" 127.0.0.1 "$PORT" "$DECL" uds.internal
  echo "== B: arbitrary UDS via TCP worker =="
  python3 "$ROOT/poc/CVE-2021-44224/poc.py" 127.0.0.1 "$PORT" "$EVIL" backend.internal
  echo "== error_log tail =="; tail -12 "$PREFIX/logs/error_log"
} > "$EVID/CVE-2021-44224/fixed_2.4.52_negative.txt" 2>&1
R2=0
grep -q 'SECRET_FROM_UDS_DECLARED' "$EVID/CVE-2021-44224/fixed_2.4.52_negative.txt" && R2=1
grep -q 'SECRET_FROM_UDS_ARBITRARY' "$EVID/CVE-2021-44224/fixed_2.4.52_negative.txt" && R2=1
grep -q 'GET /secret' /tmp/fixed-decl.log 2>/dev/null && R2=1
grep -q 'GET /secret' /tmp/fixed-evil.log 2>/dev/null && R2=1
echo "-- declared backend log --"; cat /tmp/fixed-decl.log 2>/dev/null
echo "-- evil backend log --"; cat /tmp/fixed-evil.log 2>/dev/null
stop_srv; kill "$UP1" "$UP2" 2>/dev/null || true; rm -f "$DECL" "$EVIL"
echo "44224 fixed_hit(should 0)=$R2"

### 44790 ###
echo "== [44790] fixed 2.4.52 negative =="
prep_conf "$ROOT/conf/httpd-44790.conf" "$PREFIX/conf/httpd-44790.conf"
cp -f "$ROOT/conf/lua/parsebody.lua" "$PREFIX/lua/parsebody.lua"
start_srv "$PREFIX/conf/httpd-44790.conf" || exit 2
{
  echo "== Apache/2.4.52 (Ubuntu) negative control for CVE-2021-44790 =="
  "$BIN" -v
  echo
  echo "== lua probe =="
  curl -sS -w '\nhttp=%{http_code}\n' -X POST "$BASE/parsebody" -H 'Content-Type: text/plain' --data x
  echo "== pad=3 (2.4.49: SIGSEGV) =="
  python3 "$ROOT/poc/CVE-2021-44790/poc.py" 127.0.0.1 "$PORT" /parsebody 3
  echo "== pad=0 (2.4.49: alloc abort) =="
  python3 "$ROOT/poc/CVE-2021-44790/poc.py" 127.0.0.1 "$PORT" /parsebody 0
  echo "== error_log tail =="; tail -10 "$PREFIX/logs/error_log"
} > "$EVID/CVE-2021-44790/fixed_2.4.52_negative.txt" 2>&1
R3=0
grep -q 'exit signal Segmentation fault' "$EVID/CVE-2021-44790/fixed_2.4.52_negative.txt" && R3=1
grep -q 'Memory allocation failed' "$EVID/CVE-2021-44790/fixed_2.4.52_negative.txt" && R3=1
grep -q 'parsebody survived' "$EVID/CVE-2021-44790/fixed_2.4.52_negative.txt" || echo "WARN: parsebody 未返回 survived"
stop_srv
echo "44790 fixed_hit(should 0)=$R3"

echo "===== summary (0 = fix effective) ====="
echo "41773_fixed_hit=$R1"; echo "44224_fixed_hit=$R2"; echo "44790_fixed_hit=$R3"
if [ "$R1" = 0 ] && [ "$R2" = 0 ] && [ "$R3" = 0 ]; then
  echo "RESULT: NEGATIVE CONTROL PASS (all fixed on 2.4.52 Ubuntu)"; exit 0
else
  echo "RESULT: NEGATIVE CONTROL FAIL"; exit 1
fi
