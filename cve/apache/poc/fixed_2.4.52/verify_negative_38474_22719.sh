#!/bin/bash
# 修复版负向对照（Ubuntu apache2 2.4.52-1ubuntu4.25，含发行版安全 backport）
#   CVE-2024-38474：%3f 请求应被 403（"Unsafe URL with %3f ... UnsafeAllow3F"）
#   CVE-2022-22719：multipart+无 body 不应再出现未初始化读（Valgrind 差分）
# 退出码 0 = 两个 CVE 在发行版修复版上均不再命中
#
# 说明：Ubuntu 2.4.52 的 mod_rewrite 里可见 backport 字符串
#   "AH: Unsafe URL with %%3f URL rewritten without UnsafeAllow3F"
# 证明它不是 pristine 2.4.52，而是带 2.4.60 修复的发行版构建。
set -u
ROOT="/mnt/e/强网拟态/cve/apache"
EVID="$ROOT/evidence"
PREFIX=/tmp/httpd252-cve
BIN=/usr/sbin/apache2
MODS=/usr/lib/apache2/modules
PORT=8096
BASE="http://127.0.0.1:$PORT"
HTDOCS=/opt/httpd/htdocs
LAB=/opt/httpd/lab/rewrite
mkdir -p "$PREFIX/logs" "$PREFIX/lua" "$PREFIX/htdocs" "$LAB/profiles/alice" /opt/httpd/lab/upload
cp -f /opt/httpd/conf/mime.types "$PREFIX/mime.types" 2>/dev/null || true
cp -f "$ROOT/conf/lua/parsebody.lua" "$PREFIX/lua/parsebody.lua"
printf 'PROFILE_ALICE_VISIBLE\n' > "$LAB/profiles/alice/profile.yml"
printf 'SECRET_ALICE_API_KEY=sk-live-cve38474\n' > "$LAB/profiles/alice/secret.txt"
printf '#!/bin/sh\necho "Content-Type: text/plain"\necho\necho "EXEC_MARKER uid=$(id -u) cve=2024-38474"\n' > "$LAB/profiles/alice/admin_only.sh"
chmod 755 "$LAB/profiles/alice/admin_only.sh"
printf '#!/bin/sh\nprintf "Content-Type: text/plain\\n\\n"\necho "EXEC_MARKER uid=$(id -u) cve=2024-38474 handler-mislead"\n' > /opt/httpd/lab/upload/avatar.gif
chmod 755 /opt/httpd/lab/upload/avatar.gif

echo "== fixed build =="
{
  "$BIN" -v
  sha256sum "$BIN"
  dpkg-query -W -f='apache2-bin=${Version}\n' apache2-bin 2>/dev/null
  strings "$MODS/mod_rewrite.so" | grep -i 'Unsafe URL with' || true
} > "$EVID/fixed_2.4.52_build_38474_22719.txt" 2>&1
cat "$EVID/fixed_2.4.52_build_38474_22719.txt"

prep_conf() { # $1=src $2=dst
  sed -e 's#^LoadModule unixd_module.*#\# unixd is static in Ubuntu build#' \
      -e 's#^LoadModule log_config_module.*#\# log_config is static in Ubuntu build#' \
      -e "s#modules/#$MODS/#g" \
      -e "s#^ServerRoot .*#ServerRoot \"$PREFIX\"#" \
      -e 's#^TypesConfig .*#TypesConfig /opt/httpd/conf/mime.types#' \
      -e "s#Listen 8095#Listen $PORT#" \
      -e "s#/tmp/cve-2024-38474#$PREFIX#g" \
      -e "s#/tmp/cve-2022-22719#$PREFIX#g" \
      "$1" > "$2"
  sed -i "1i LoadModule mpm_event_module $MODS/mod_mpm_event.so" "$2"
  sed -i "1i # generated by verify_negative_38474_22719.sh for Apache/2.4.52 (Ubuntu)" "$2"
}

stop_srv() {
  [ -n "${HPID:-}" ] && kill "$HPID" 2>/dev/null || true
  sleep 0.6
  [ -n "${HPID:-}" ] && kill -9 "$HPID" 2>/dev/null || true
  HPID=""
}

start_srv() { # $1 conf
  stop_srv
  : > "$PREFIX/error_log"; : > "$PREFIX/access_log"
  cd "$PREFIX"
  "$BIN" -f "$1" -DFOREGROUND > "$PREFIX/logs/console.log" 2>&1 &
  HPID=$!
  local ok=0
  for i in $(seq 1 80); do
    local code
    code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 2 "$BASE/" 2>/dev/null || true)
    if [ -n "$code" ] && [ "$code" != "000" ]; then ok=1; break; fi
    sleep 0.25
  done
  if [ "$ok" != 1 ]; then
    echo "FIXED SERVER START FAILED"; tail -25 "$PREFIX/logs/console.log" "$PREFIX/error_log" 2>/dev/null
    return 1
  fi
}

### CVE-2024-38474 负向 ###
echo "== [38474] fixed-version negative control =="
prep_conf "$ROOT/conf/CVE-2024-38474.conf" "$PREFIX/conf-38474.conf"
if ! start_srv "$PREFIX/conf-38474.conf"; then stop_srv; exit 2; fi
{
  echo "== Apache/2.4.52 (Ubuntu 2.4.52-1ubuntu4.25, CVE-2024-38474 backport) =="
  "$BIN" -v
  echo
  for path in "/user/alice" "/user/alice/secret.txt" "/user/alice/secret.txt%3F" \
              "/user/alice/secret.txt%3f" "/user/alice/secret.txt%3Fjunk" \
              "/user/alice/secret.txt%253F" "/user/alice/admin_only.sh%3F" \
              "/get/avatar.gif%3Ffake.sh" "/get/avatar.gif"; do
    code=$(curl -sS --path-as-is --max-time 5 -o /tmp/fixed_body.txt \
                -w '%{http_code}' "$BASE$path" 2>/dev/null || true)
    body=$(head -c 120 /tmp/fixed_body.txt | tr '\n' ' ')
    echo "fixed_request $code $path  body=[$body]"
  done
  echo "== error_log: Unsafe URL with %3f =="
  grep -a 'Unsafe URL with' "$PREFIX/error_log" | head -5
  echo "== error_log tail =="
  tail -5 "$PREFIX/error_log"
} > "$EVID/CVE-2024-38474/fixed_2.4.52_negative.txt" 2>&1
cp -f "$PREFIX/error_log" "$EVID/CVE-2024-38474/fixed_2.4.52_error_log.txt" 2>/dev/null || true
R1=0
grep -q 'fixed_request 200 /user/alice  body=\[PROFILE_ALICE_VISIBLE' "$EVID/CVE-2024-38474/fixed_2.4.52_negative.txt" || R1=1
for p in 'secret.txt%3F' 'secret.txt%3f' 'secret.txt%3Fjunk' 'admin_only.sh%3F' 'avatar.gif%3Ffake.sh'; do
  grep -q "fixed_request 403 .*$p" "$EVID/CVE-2024-38474/fixed_2.4.52_negative.txt" || R1=1
done
N403LOG=$(grep -a -c 'Unsafe URL with' "$PREFIX/error_log" 2>/dev/null || true)
[ "${N403LOG:-0}" -ge 3 ] || R1=1
grep -q 'SECRET_ALICE_API_KEY' "$EVID/CVE-2024-38474/fixed_2.4.52_negative.txt" && R1=1
grep -q 'EXEC_MARKER' "$EVID/CVE-2024-38474/fixed_2.4.52_negative.txt" && R1=1
stop_srv
echo "38474 fixed_hit(should 0)=$R1"

### CVE-2022-22719 负向（Valgrind 差分） ###
echo "== [22719] fixed-version negative control =="
prep_conf "$ROOT/conf/CVE-2022-22719.conf" "$PREFIX/conf-22719.conf"
: > "$PREFIX/error_log"; : > "$PREFIX/access_log"
rm -f "$PREFIX"/vg.*.log
cd "$PREFIX"
valgrind --tool=memcheck --track-origins=yes --num-callers=20 --error-limit=no \
         --log-file="$PREFIX/vg.%p.log" \
         "$BIN" -X -f "$PREFIX/conf-22719.conf" > "$PREFIX/logs/console22719.log" 2>&1 &
VPID=$!
ok=0
for i in $(seq 1 160); do
  code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 2 "$BASE/" 2>/dev/null || true)
  if [ -n "$code" ] && [ "$code" != "000" ]; then ok=1; break; fi
  sleep 0.5
done
if [ "$ok" != 1 ]; then
  echo "FIXED VG SERVER START FAILED"; tail -20 "$PREFIX/logs/console22719.log"; kill "$VPID" 2>/dev/null; exit 2
fi
VGLOG=$(ls "$PREFIX"/vg.*.log 2>/dev/null | head -1)
echo "valgrind_pid=$VPID log=$VGLOG"
count_uninit() {
  [ -f "$VGLOG" ] || { echo 0; return; }
  local n
  n=$(grep -a -c 'uninitialised' "$VGLOG" 2>/dev/null)
  echo "${n:-0}"
}
{
  echo "== Apache/2.4.52 (Ubuntu) + Valgrind, CVE-2022-22719 negative control =="
  echo "P1 negative phase:"
  curl -sS --max-time 20 -o /tmp/f1.txt -w 'neg_plain=%{http_code}\n' \
       -H 'Content-Type: text/plain' "$BASE/parsebody" || true
  curl -sS --max-time 20 -o /tmp/f2.txt -w 'neg_noctype=%{http_code}\n' \
       "$BASE/parsebody" || true
  sleep 1
  NEG_ERR=$(count_uninit)
  echo "negative_phase_uninit=$NEG_ERR"
  echo "positive phase:"
  curl -sS --max-time 20 -o /tmp/f3.txt -w 'pos_get_nobody=%{http_code}\n' \
       -H 'Content-Type: multipart/form-data; boundary=ABCXYZ' \
       -H 'Content-Length: 0' "$BASE/parsebody" || true
  curl -sS --max-time 20 -o /tmp/f4.txt -w 'pos_post_cl0=%{http_code}\n' -X POST \
       -H 'Content-Type: multipart/form-data; boundary=ABCXYZ' \
       -H 'Content-Length: 0' "$BASE/parsebody" || true
  sleep 2
  POS_ERR=$(count_uninit)
  echo "positive_phase_uninit=$POS_ERR"
  echo "--- uninit hits in fixed mod_lua (expect none) ---"
  grep -a -B2 -A8 'uninitialised' "$VGLOG" 2>/dev/null | head -40 || true
  echo "--- valgrind summary-ish ---"
  grep -a 'ERROR SUMMARY' "$VGLOG" 2>/dev/null || true
} > "$EVID/CVE-2022-22719/fixed_2.4.52_negative.txt" 2>&1
sleep 1
kill "$VPID" 2>/dev/null || true
for i in $(seq 1 20); do kill -0 "$VPID" 2>/dev/null || break; sleep 0.3; done
kill -9 "$VPID" 2>/dev/null || true
sleep 0.5
cp -f "$VGLOG" "$EVID/CVE-2022-22719/fixed_2.4.52_valgrind.log" 2>/dev/null || true
cat "$EVID/CVE-2022-22719/fixed_2.4.52_negative.txt"
R2=0
NEG=$(grep -a -o 'negative_phase_uninit=[0-9]*' "$EVID/CVE-2022-22719/fixed_2.4.52_negative.txt" | tail -1 | cut -d= -f2)
POS=$(grep -a -o 'positive_phase_uninit=[0-9]*' "$EVID/CVE-2022-22719/fixed_2.4.52_negative.txt" | tail -1 | cut -d= -f2)
[ "${POS:-0}" -gt 0 ] && R2=1
[ "${NEG:-0}" -gt 0 ] && R2=1
grep -q 'pos_get_nobody=200' "$EVID/CVE-2022-22719/fixed_2.4.52_negative.txt" || R2=1
grep -q 'pos_post_cl0=200' "$EVID/CVE-2022-22719/fixed_2.4.52_negative.txt" || R2=1
echo "22719 fixed_hit(should 0)=$R2"

echo "===== summary (0 = fix effective) ====="
echo "38474_fixed_hit=$R1"
echo "22719_fixed_hit=$R2"
if [ "$R1" = 0 ] && [ "$R2" = 0 ]; then
  echo "RESULT: NEGATIVE CONTROL PASS (38474/22719 fixed on Ubuntu 2.4.52 backport)"
  exit 0
else
  echo "RESULT: NEGATIVE CONTROL FAIL"
  exit 1
fi
